#include <iostream>

int main()
{
    std::cout << 5 << '\n'; // prints the literal number 5
    std::cout << -6.7 << '\n'; // prints the literal number -6.7
    std::cout << 'H' << '\n'; // prints the literal character 'H'
    std::cout << "Hello" << '\n'; // prints the literal string "Hello"

    return 0;
}